/// 编号(1–32)→ RGB。越界(理论不会,调用方先 [`parse_color`] 校验)回退白。
pub fn rgb(idx: u8) -> [u8; 3] {
    let i = idx as usize;
    if (1..=32).contains(&i) {
        let (r, g, b) = PALETTE[i - 1];
        [r, g, b]
    } else {
        [255, 255, 255]
    }
}

/// 编号(1–32)→ 中文名。越界回退 `"?"`。
pub fn name(idx: u8) -> &'static str {
    let i = idx as usize;
    if (1..=32).contains(&i) {
        NAMES[i - 1]
    } else {
        "?"
    }
}

/// 容错解析一个颜色输入 → 编号(1–32)。纯数字按编号校验;否则查中文名 / 别名(大小写不敏感)。
pub fn parse_color(s: &str) -> Option<u8> {
    let s = s.trim();
    if s.is_empty() {
        return None;
    }
    // 纯数字:当编号,校验 1–32。
    if let Ok(n) = s.parse::<i64>() {
        return (1..=32).contains(&n).then_some(n as u8);
    }
    // 中文名直配(不区分大小写对中文无影响,但英文别名需小写)。
    if let Some(pos) = NAMES.iter().position(|&n| n == s) {
        return Some(pos as u8 + 1);
    }
    let low = s.to_lowercase();
    ALIASES.iter().find(|(a, _)| *a == low).map(|(_, idx)| *idx)
}

/// 色板的文字图例:`"1深红 2红 3橙红 …"`(配合编号色块图发出)。
pub fn legend() -> String {
    (1..=32u8).map(|i| format!("{i}{}", name(i))).collect::<Vec<_>>().join(" ")
}
